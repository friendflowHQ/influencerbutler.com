// Idempotent codemod: put the walkthrough video (lazy privacy-mode embed +
// collapsed transcript + VideoObject JSON-LD) on the static marketing pages:
//
//   public/features/<featureSlug>.html   one block per feature page that has a catalog video
//   public/index.html                    the Getting Started video ("See it run")
//   public/download.html                 the Getting Started video ("your first five minutes")
//
// and a "Videos" link in every static footer's Product column.
//
// Source of truth is content/tutorials/_video-catalog.json (+ _transcripts.json),
// both generated by scripts/generate-transcripts.mjs, so this needs no desktop
// repo at build time and runs from `prebuild`. Blocks are wrapped in
// <!-- ib-video:start --> ... <!-- ib-video:end --> markers: an existing block is
// replaced in place (ids, titles and transcripts change when videos re-publish),
// a missing one is inserted before the page's CTA section, and files are only
// written when their content actually changes, so a second run is a no-op.
import { readFile, writeFile, readdir } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import {
  SITE_ORIGIN,
  escapeHtml,
  iframeHtml,
  jsonLdScript,
  minutesLabel,
  transcriptHtml,
  videoObject,
} from "./lib/video-jsonld.mjs";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(__dirname, "..");
const publicDir = path.join(repoRoot, "public");
const contentDir = path.join(repoRoot, "content", "tutorials");

const START = "<!-- ib-video:start -->";
const END = "<!-- ib-video:end -->";

async function readJson(file) {
  return JSON.parse(await readFile(file, "utf8"));
}

async function* walk(dir) {
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) yield* walk(full);
    else if (entry.isFile() && entry.name.endsWith(".html")) yield full;
  }
}

const eolOf = (s) => (s.includes("\r\n") ? "\r\n" : "\n");

function indentLines(text, indent, eol) {
  return text
    .split("\n")
    .map((l) => (l ? indent + l : l))
    .join(eol);
}

/**
 * Build the block markup (without indentation).
 * variant: "feature" | "home" | "download"
 */
function buildBlock({ video, extras, transcripts, pageUrl, variant }) {
  const title = escapeHtml(video.title);
  const transcript = transcriptHtml(transcripts[video.videoId]);
  const copy = {
    feature: {
      label: "",
      heading: `Watch the ${minutesLabel(video.seconds)} walkthrough`,
      lead: `${title}. Recorded inside the app and narrated start to finish.`,
      id: "walkthrough",
    },
    home: {
      label: '<span class="section-label">Watch</span>',
      heading: "See it run in two minutes",
      lead: `${title}. A real screen recording of the app, narrated start to finish, so you know what you are installing.`,
      id: "see-it-run",
    },
    download: {
      label: "",
      heading: "Installed? Here is your first five minutes.",
      lead: `${title}. Where everything is and how to run your first butler.`,
      id: "first-five-minutes",
    },
  }[variant];

  const more = extras.length
    ? `<div class="feature-video-more"><h3>More walkthroughs</h3><ul>` +
      extras
        .map(
          (v) =>
            `<li><a href="/videos/${escapeHtml(v.slug)}">${escapeHtml(v.title)}</a> <span class="feature-video-duration">(${minutesLabel(v.seconds).replace("-minute", " min")})</span></li>`,
        )
        .join("") +
      `</ul></div>`
    : "";

  const inner = [
    copy.label,
    `<h2 id="${copy.id}-title">${copy.heading}</h2>`,
    `<p class="feature-video-lead">${copy.lead}</p>`,
    `<div class="feature-video-frame">${iframeHtml(video)}</div>`,
    transcript,
    more,
    `<p class="feature-video-links"><a href="/videos/${escapeHtml(video.slug)}">Open on the videos page</a> <span aria-hidden="true">&middot;</span> <a href="/videos">All walkthrough videos</a></p>`,
  ]
    .filter(Boolean)
    .join("\n  ");

  const sectionClass = variant === "home" ? "feature-video home-video anim-up" : "feature-video anim-up";
  const body =
    variant === "home"
      ? `<div class="container">\n  ${inner}\n</div>`
      : inner;
  return [
    START,
    `<section class="${sectionClass}" id="${copy.id}" aria-labelledby="${copy.id}-title">`,
    `  ${body}`,
    `</section>`,
    jsonLdScript(videoObject(video, pageUrl)),
    END,
  ].join("\n");
}

/** Replace an existing block or insert a new one at `insertAt(html)`. */
function applyBlock(html, block, insertAt) {
  const eol = eolOf(html);
  const existing = html.match(/([ \t]*)<!-- ib-video:start -->[\s\S]*?<!-- ib-video:end -->/);
  if (existing) {
    return html.replace(existing[0], indentLines(block, existing[1], eol));
  }
  const pos = insertAt(html);
  if (!pos) return null;
  const { index, indent, after } = pos;
  const rendered = indentLines(block, indent, eol);
  return after
    ? html.slice(0, index) + eol + eol + rendered + html.slice(index)
    : html.slice(0, index) + rendered + eol + eol + indent + html.slice(index + indent.length);
}

// Insertion points.
const beforeFeatureCta = (html) => {
  const m = html.match(/([ \t]*)<section class="feature-cta/);
  return m ? { index: m.index, indent: m[1] } : null;
};
const beforePricing = (html) => {
  const m = html.match(/([ \t]*)<!-- =+ PRICING =+ -->/);
  return m ? { index: m.index, indent: m[1] } : null;
};
const afterDownloadNotes = (html) => {
  const start = html.indexOf('<div class="download-notes">');
  if (start === -1) return null;
  const m = html.slice(start).match(/([ \t]*)<\/section>/);
  if (!m) return null;
  const index = start + m.index + m[0].length;
  return { index, indent: m[1], after: true };
};

async function main() {
  const catalog = (await readJson(path.join(contentDir, "_video-catalog.json"))).videos || [];
  const transcripts = (await readJson(path.join(contentDir, "_transcripts.json"))).transcripts || {};

  const byFeature = new Map();
  for (const v of catalog) {
    if (!v.featureSlug) continue;
    if (!byFeature.has(v.featureSlug)) byFeature.set(v.featureSlug, []);
    byFeature.get(v.featureSlug).push(v);
  }
  for (const list of byFeature.values()) {
    list.sort((a, b) => (a.featureRank ?? 100) - (b.featureRank ?? 100) || a.title.localeCompare(b.title));
  }
  const forPage = (page) => catalog.find((v) => Array.isArray(v.pages) && v.pages.includes(page));

  const jobs = [];
  for (const [slug, list] of byFeature) {
    jobs.push({
      file: path.join(publicDir, "features", `${slug}.html`),
      pageUrl: `${SITE_ORIGIN}/features/${slug}`,
      video: list[0],
      extras: list.slice(1),
      variant: "feature",
      insertAt: beforeFeatureCta,
    });
  }
  const home = forPage("index.html");
  if (home) {
    jobs.push({ file: path.join(publicDir, "index.html"), pageUrl: `${SITE_ORIGIN}/`, video: home, extras: [], variant: "home", insertAt: beforePricing });
  }
  const dl = forPage("download.html");
  if (dl) {
    jobs.push({ file: path.join(publicDir, "download.html"), pageUrl: `${SITE_ORIGIN}/download`, video: dl, extras: [], variant: "download", insertAt: afterDownloadNotes });
  }

  let modified = 0;
  let unchanged = 0;
  let skipped = 0;
  const touched = new Set();
  for (const job of jobs) {
    let html;
    try {
      html = await readFile(job.file, "utf8");
    } catch {
      console.warn(`  skip  ${path.relative(repoRoot, job.file)} (missing)`);
      skipped++;
      continue;
    }
    const block = buildBlock({ ...job, transcripts });
    const next = applyBlock(html, block, job.insertAt);
    if (next === null) {
      console.warn(`  skip  ${path.relative(repoRoot, job.file)} (no insertion point)`);
      skipped++;
      continue;
    }
    if (next !== html) {
      await writeFile(job.file, next);
      touched.add(job.file);
      modified++;
      console.log(`  video ${path.relative(repoRoot, job.file)} <- ${job.video.videoId}`);
    } else {
      unchanged++;
    }
  }

  // Footer "Videos" link next to "Free Tools" on every static page.
  let footerAdded = 0;
  for await (const file of walk(publicDir)) {
    const html = await readFile(file, "utf8");
    if (!/<a href="\/tools">Free Tools<\/a>/.test(html) || /href="\/videos"[^>]*>Videos</.test(html)) continue;
    const eol = eolOf(html);
    const next = html.replace(
      /(\r?\n)([ \t]*)<a href="\/tools">Free Tools<\/a>/,
      (m, nl, indent) => `${m}${eol}${indent}<a href="/videos">Videos</a>`,
    );
    if (next !== html) {
      await writeFile(file, next);
      footerAdded++;
    }
  }

  console.log(
    `inject-feature-videos: ${jobs.length} pages, ${modified} modified, ${unchanged} unchanged, ${skipped} skipped; footer links added: ${footerAdded}`,
  );
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
