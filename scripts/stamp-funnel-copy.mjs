#!/usr/bin/env node
// Restamps src/lib/funnel-copy-dates.ts (COPY_UPDATED_AT + COPY_FINGERPRINTS).
//
// The funnel copy lives in TypeScript (system-funnels.ts and the *-emails.ts
// copy files), and no script in this repo loads TS directly, so this runs the
// fingerprint test in "stamp mode" through vitest (which already resolves the
// @/ alias and TS), reads the fingerprints it writes, and then:
//   - keys whose fingerprint is unchanged keep their date
//   - changed or new keys get today's date (or --date=YYYY-MM-DD)
//   - keys that no longer exist are dropped
//
// Usage (same on Windows PowerShell and Mac Terminal):
//   node scripts/stamp-funnel-copy.mjs            # rewrite the file
//   node scripts/stamp-funnel-copy.mjs --dry      # show what would change
//   node scripts/stamp-funnel-copy.mjs --date=2026-11-08

import { spawnSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const TARGET = path.join(ROOT, "src", "lib", "funnel-copy-dates.ts");
const TEST = "src/lib/__tests__/funnel-copy-dates.test.ts";
const BEGIN = "// <stamp-funnel-copy:begin>";
const END = "// <stamp-funnel-copy:end>";

const args = process.argv.slice(2);
const dry = args.includes("--dry");
const dateArg = args.find((a) => a.startsWith("--date="))?.slice("--date=".length);

function localToday() {
  const d = new Date();
  const p = (n) => String(n).padStart(2, "0");
  return `${d.getFullYear()}-${p(d.getMonth() + 1)}-${p(d.getDate())}`;
}

const today = dateArg ?? localToday();
if (!/^\d{4}-\d{2}-\d{2}$/.test(today)) {
  console.error(`Invalid --date: ${today} (want YYYY-MM-DD)`);
  process.exit(1);
}

// 1. Current fingerprints from the test, in stamp mode.
const outFile = path.join(os.tmpdir(), `funnel-copy-stamp-${process.pid}-${Date.now()}.json`);
const run = spawnSync("npx", ["vitest", "run", TEST], {
  cwd: ROOT,
  env: { ...process.env, FUNNEL_COPY_STAMP_OUT: outFile },
  stdio: "inherit",
  shell: process.platform === "win32",
});
if (run.status !== 0 || !fs.existsSync(outFile)) {
  console.error("stamp-funnel-copy: vitest did not produce fingerprints (see output above).");
  process.exit(1);
}
const { fingerprints: current } = JSON.parse(fs.readFileSync(outFile, "utf8"));
fs.rmSync(outFile, { force: true });

// 2. Existing maps from the generated block.
const src = fs.readFileSync(TARGET, "utf8");
const b = src.indexOf(BEGIN);
const e = src.indexOf(END);
if (b < 0 || e < 0 || e < b) {
  console.error(`stamp-funnel-copy: markers not found in ${TARGET}`);
  process.exit(1);
}
const block = src.slice(b, e);
function readMap(name) {
  const m = block.match(new RegExp(`export const ${name}[^=]*=\\s*\\{([\\s\\S]*?)\\n\\};`));
  const out = {};
  if (!m) return out;
  for (const line of m[1].matchAll(/"([^"]+)":\s*"([^"]+)"/g)) out[line[1]] = line[2];
  return out;
}
const oldDates = readMap("COPY_UPDATED_AT");
const oldPrints = readMap("COPY_FINGERPRINTS");

// 3. Merge.
const keys = Object.keys(current).sort();
const dates = {};
const changed = [];
const added = [];
for (const k of keys) {
  if (oldPrints[k] === current[k] && oldDates[k]) {
    dates[k] = oldDates[k];
  } else {
    dates[k] = today;
    (k in oldPrints ? changed : added).push(k);
  }
}
const removed = Object.keys(oldPrints).filter((k) => !(k in current));

console.log(
  `stamp-funnel-copy: ${keys.length} keys, ${changed.length} changed, ${added.length} new, ${removed.length} removed (date ${today})`,
);
for (const k of changed) console.log(`  changed  ${k}`);
for (const k of added) console.log(`  new      ${k}`);
for (const k of removed) console.log(`  removed  ${k}`);

if (dry) process.exit(0);

// 4. Rewrite the block.
const lines = (map) => keys.map((k) => `  ${JSON.stringify(k)}: ${JSON.stringify(map[k])},`).join("\n");
const generated = [
  `${BEGIN} generated by scripts/stamp-funnel-copy.mjs, do not hand-edit`,
  "export const COPY_UPDATED_AT: Record<string, string> = {",
  lines(dates),
  "};",
  "",
  "export const COPY_FINGERPRINTS: Record<string, string> = {",
  lines(current),
  "};",
  "",
].join("\n");
// Keep the file's own line endings.
const eol = src.includes("\r\n") ? "\r\n" : "\n";
const next = src.slice(0, b) + generated.replace(/\n/g, eol) + src.slice(e);
fs.writeFileSync(TARGET, next, "utf8");
console.log(`stamp-funnel-copy: wrote ${path.relative(ROOT, TARGET)}`);
