/**
 * Code-default date for a funnel content key: the exact key's date, else the
 * nearest fallback key's (a tailored key with no own copy renders its
 * fallback, so it carries that date). null when nothing is stamped.
 */
export function copyUpdatedFor(funnel: string, key: string): string | null {
  for (const k of contentKeyFallbacks(key)) {
    const d = COPY_UPDATED_AT[`${funnel}:${k}`];
    if (d) return d;
  }
  return null;
}

/** Newest code date across a funnel's keys (null when none stamped). */
export function newestCopyDateForFunnel(funnel: string): string | null {
  let best: string | null = null;
  const prefix = `${funnel}:`;
  for (const [k, d] of Object.entries(COPY_UPDATED_AT)) {
    if (!k.startsWith(prefix)) continue;
    if (!best || d > best) best = d;
  }
  return best;
}
